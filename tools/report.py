"""Summarize learner results.

  python3 tools/report.py                 # summary of every attempt + writes progress/tag-stats.md
  python3 tools/report.py results/x.json  # one attempt, item by item
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def attempts():
    files = sorted((ROOT / "results").glob("*.json")) + sorted((ROOT / "results" / "drafts").glob("*.json"))
    for f in files:
        yield f, json.loads(f.read_text(encoding="utf-8"))


def show_one(path):
    d = json.loads(Path(path).read_text(encoding="utf-8"))
    print(f"{d['lessonId']}  final={d.get('final')}  minutes={d.get('durationMin')}  plays={d.get('audioPlays')}")
    print(f"score={d.get('score')}  sectionMinutes={d.get('sectionMinutes')}")
    first = d.get("firstTry", {})
    for i in d["items"]:
        mark = {True: "OK", False: "XX", None: "??"}[i["correct"]]
        if i["type"] in ("write", "speak"):
            given = i.get("given")
            if isinstance(given, dict):
                given = f"[{given.get('seconds')}s rec {given.get('recording')}] {given.get('transcript', '')}"
            print(f"\n{i['id']} {i['type']} ({', '.join(i['tags'])}):\n{given or '(not done)'}\n")
            continue
        ft = "" if i["id"] not in first else f" firstTry={'OK' if first[i['id']] else 'XX'}"
        print(f"{i['id']:5} {mark} {str(i.get('given'))[:60]:60} | expected: {i.get('expected')}  [{', '.join(i['tags'])}]{ft}")


def tag_stats():
    stats = defaultdict(lambda: {"seen": 0, "wrong": 0, "examples": []})
    for f, d in attempts():
        first = d.get("firstTry", {})
        for i in d["items"]:
            if i.get("given") in (None, "", []):
                continue
            correct = first.get(i["id"], i["correct"])
            if correct is None:
                continue
            for t in i["tags"]:
                s = stats[t]
                s["seen"] += 1
                if not correct:
                    s["wrong"] += 1
                    s["examples"].append(f"{d['lessonId']}/{i['id']}: '{i.get('given')}' → '{i.get('expected')}'")
    lines = ["# Tag stats (generated by tools/report.py – do not edit)", "",
             "| tag | wrong/seen | error rate | latest wrong examples |", "|---|---|---|---|"]
    for t, s in sorted(stats.items(), key=lambda kv: (-kv[1]["wrong"] / kv[1]["seen"], -kv[1]["seen"])):
        ex = "; ".join(s["examples"][-3:]).replace("|", "/")
        lines.append(f"| `{t}` | {s['wrong']}/{s['seen']} | {round(100 * s['wrong'] / s['seen'])}% | {ex} |")
    out = ROOT / "progress" / "tag-stats.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) > 1:
        show_one(sys.argv[1])
    else:
        for f, d in attempts():
            print(f"{f.relative_to(ROOT)}  final={d.get('final')}  score={d.get('score')}")
        print()
        tag_stats()
